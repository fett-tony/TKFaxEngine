    private sealed class OneWayLine : IDisposable {
        private readonly CodecMunge _munge; private readonly float[] _nearFilter, _farFilter, _nearBuffer = new float[129], _farBuffer = new float[129]; private int _nearPointer, _farPointer, _delayPointer; private readonly short[] _delay = new short[8]; private readonly Awgn _nearNoise, _farNoise; public readonly float NearCoEcho, FarCpeEcho; public float DcOffset = 0.0f;
        public OneWayLine(int model, float noise, float echoCpe, float echoCo, int codec, int rbsPattern, int seed) { if ((uint)model >= (uint)LineModels.Length) throw new ArgumentOutOfRangeException(nameof(model)); _nearFilter = LineModels[model]; _farFilter = LineModels[model]; _nearNoise = new Awgn(seed, noise - 3.02); _farNoise = new Awgn(seed, noise - 3.02); _munge = new CodecMunge(codec, rbsPattern); NearCoEcho = MathF.Pow(10, echoCo / 20); _ = echoCpe; FarCpeEcho = 0; }
        private float Filter(float value, float[] coefficients, float[] history, ref int pointer, Awgn noise) { history[pointer] = value; if (++pointer == history.Length) pointer = 0; float sum = 0; int p = pointer; for (int j = 0; j < coefficients.Length; j++) { sum += coefficients[j] * history[p]; if (++p >= history.Length) p = 0; } return sum + noise.NextSample(); }
        public float Near(float value) => Filter(value, _nearFilter, _nearBuffer, ref _nearPointer, _nearNoise); public float Far(float value) => Filter(value, _farFilter, _farBuffer, ref _farPointer, _farNoise); public float Digital(float value) { short munged = _munge.Process(Saturate(value)); short delayed = _delay[_delayPointer]; _delay[_delayPointer] = munged; if (++_delayPointer >= _delay.Length) _delayPointer = 0; return delayed; }
        public void Dispose() => _munge.Dispose();
    }
    private sealed class BidirectionalLineModel : IDisposable {
        private readonly OneWayLine _line1, _line2; private float _fout1, _fout2;
        public BidirectionalLineModel(int model1, float noise1, float echoCpe1, float echoCo1, int model2, float noise2, float echoCpe2, float echoCo2, int codec, int rbsPattern) { _line1 = new OneWayLine(model1, noise1, echoCpe1, echoCo1, codec, rbsPattern, 1234567); _line2 = new OneWayLine(model2, noise2, echoCpe2, echoCo2, codec, rbsPattern, 7654321); }
        public void Process(short[] output1, short[] input1, short[] output2, short[] input2, int samples) { for (int i = 0; i < samples; i++) { float in1 = input1[i], in2 = input2[i]; float tmp1 = in1 + _fout2 * _line1.NearCoEcho, tmp2 = in2 + _fout1 * _line2.NearCoEcho; _fout1 = _line1.Near(tmp1); _fout2 = _line2.Near(tmp2); float out1 = _line1.Digital(_fout1), out2 = _line2.Digital(_fout2); _fout1 = out1; _fout2 = out2; out1 += in2 * _line1.FarCpeEcho; out2 += in1 * _line2.FarCpeEcho; output1[i] = Saturate(_line1.Far(out1) + _line1.DcOffset); output2[i] = Saturate(_line2.Far(out2) + _line2.DcOffset); } }
        public void Dispose() { _line1.Dispose(); _line2.Dispose(); }
    }
    private static short Saturate(double value) => value > short.MaxValue ? short.MaxValue : value < short.MinValue ? short.MinValue : (short)Math.Round(value);

    private sealed class Pcm16WaveReader : IDisposable {
        private readonly BinaryReader _reader;
        private readonly int _channels;
        private long _remaining;
        public Pcm16WaveReader(string path, int expectedRate, int expectedChannels) {
            _reader = new BinaryReader(File.OpenRead(path));
            if (new string(_reader.ReadChars(4)) != "RIFF") throw new InvalidDataException("Not RIFF");
            _reader.ReadUInt32();
            if (new string(_reader.ReadChars(4)) != "WAVE") throw new InvalidDataException("Not WAVE");
            int format = 0, channels = 0, rate = 0, bits = 0;
            while (_reader.BaseStream.Position + 8 <= _reader.BaseStream.Length) {
                string id = new string(_reader.ReadChars(4));
                int size = _reader.ReadInt32();
                long next = _reader.BaseStream.Position + size + (size & 1);
                if (id == "fmt ") {
                    format = _reader.ReadUInt16(); channels = _reader.ReadUInt16(); rate = _reader.ReadInt32();
                    _reader.ReadInt32(); _reader.ReadUInt16(); bits = _reader.ReadUInt16();
                } else if (id == "data") { _remaining = size; break; }
                _reader.BaseStream.Position = next;
            }
            if (format != 1 || bits != 16 || channels != expectedChannels || rate != expectedRate)
                throw new InvalidDataException($"Unexpected WAV format in '{path}'.");
            _channels = channels;
        }
        public int ReadFrames(Span<short> destination) {
            int count = 0;
            while (count < destination.Length && _remaining >= 2L * _channels) {
                destination[count++] = _reader.ReadInt16();
                for (int channel = 1; channel < _channels; channel++) _reader.ReadInt16();
                _remaining -= 2L * _channels;
            }
            return count;
        }
        public void Dispose() => _reader.Dispose();
    }

    private sealed class Pcm16WaveWriter : IDisposable {
        private readonly BinaryWriter _writer;
        private readonly int _rate;
        private readonly short _channels;
        private long _samples;
        public Pcm16WaveWriter(string path, int rate, int channels) {
            _rate = rate; _channels = checked((short)channels); _writer = new BinaryWriter(File.Create(path));
            _writer.Write(global::System.Text.Encoding.ASCII.GetBytes("RIFF")); _writer.Write(0);
            _writer.Write(global::System.Text.Encoding.ASCII.GetBytes("WAVEfmt ")); _writer.Write(16); _writer.Write((short)1);
            _writer.Write(_channels); _writer.Write(_rate); _writer.Write(_rate * _channels * 2);
            _writer.Write((short)(_channels * 2)); _writer.Write((short)16);
            _writer.Write(global::System.Text.Encoding.ASCII.GetBytes("data")); _writer.Write(0);
        }
        public void WriteFrames(ReadOnlySpan<short> samples) {
            foreach (short sample in samples) _writer.Write(sample);
            _samples += samples.Length;
        }
        public void Dispose() {
            long end = _writer.BaseStream.Position;
            _writer.BaseStream.Position = 4; _writer.Write(checked((int)(end - 8)));
            _writer.BaseStream.Position = 40; _writer.Write(checked((int)(_samples * 2)));
            _writer.BaseStream.Position = end; _writer.Dispose();
        }
    }

