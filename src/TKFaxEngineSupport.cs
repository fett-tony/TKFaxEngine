/// </summary>
public static class FastConvert {
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public static int lrint(double value) {
        return checked((int)Math.Round(value, MidpointRounding.ToEven));
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public static int lrintf(float value) {
        return checked((int)Math.Round(value, MidpointRounding.ToEven));
