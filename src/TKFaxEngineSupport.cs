/// <summary>
/// Fast approximate four-quadrant arc tangent from arctan2.h. The result is a
/// signed 32-bit phase where +/- pi maps to the Int32 boundary.
/// </summary>
public static class FastArcTan {
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public static int arctan2(float y, float x) {
        if (y == 0.0f)
            return x < 0.0f ? int.MinValue : 0;

        if (x == 0.0f)
            return y < 0.0f
                ? unchecked((int)0xC0000000u)
                : 0x40000000;

        float absoluteY = MathF.Abs(y);
        float angle = x < 0.0f
            ? 3.0f - (x + absoluteY) / (absoluteY - x)
            : 1.0f - (x - absoluteY) / (absoluteY + x);

        angle *= 536_870_912.0f;
        if (y < 0.0f)
            angle = -angle;

        return unchecked((int)angle);
    }
}

