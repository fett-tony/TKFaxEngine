/// <summary>
/// Managed port of saturated.h. Operations clamp instead of overflowing.
/// </summary>
public static class Saturated {
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public static short saturate16(int amplitude) {
        return (short)Math.Clamp(amplitude, short.MinValue, short.MaxValue);
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public static short saturate15(int amplitude) {
        return (short)Math.Clamp(amplitude, -16_384, 16_383);
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public static ushort saturateu16(int amplitude) {
        return (ushort)Math.Clamp(amplitude, ushort.MinValue, ushort.MaxValue);
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public static byte saturateu8(int amplitude) {
        return (byte)Math.Clamp(amplitude, byte.MinValue, byte.MaxValue);
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public static short fsaturatef(float amplitude) {
        if (amplitude > short.MaxValue)
            return short.MaxValue;
        if (amplitude < short.MinValue)
            return short.MinValue;

        return (short)FastConvert.lrintf(amplitude);
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public static short fsaturate(double amplitude) {
        if (amplitude > short.MaxValue)
            return short.MaxValue;
        if (amplitude < short.MinValue)
            return short.MinValue;

        return (short)FastConvert.lrint(amplitude);
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public static short ffastsaturatef(float amplitude) {
        if (amplitude > short.MaxValue)
            return short.MaxValue;
        if (amplitude < short.MinValue)
            return short.MinValue;

        return (short)FastConvert.lfastrintf(amplitude);
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public static short ffastsaturate(double amplitude) {
        if (amplitude > short.MaxValue)
            return short.MaxValue;
        if (amplitude < short.MinValue)
            return short.MinValue;

        return (short)FastConvert.lfastrint(amplitude);
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public static float ffsaturatef(float amplitude) {
        return Math.Clamp(amplitude, short.MinValue, short.MaxValue);
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public static double ffsaturate(double amplitude) {
        return Math.Clamp(amplitude, short.MinValue, short.MaxValue);
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public static short sat_add16(short x, short y) {
        return saturate16(x + y);
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public static int sat_add32(int x, int y) {
        long result = (long)x + y;
        return (int)Math.Clamp(result, int.MinValue, int.MaxValue);
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public static short sat_sub16(short x, short y) {
        return saturate16(x - y);
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public static int sat_sub32(int x, int y) {
        long result = (long)x - y;
        return (int)Math.Clamp(result, int.MinValue, int.MaxValue);
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public static short sat_mul16(short x, short y) {
        int product = x * y;
        if (product == 0x40000000)
            return short.MaxValue;

        return (short)(product >> 15);
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public static int sat_mul32_16(short x, short y) {
        int product = x * y;
        if (product == 0x40000000)
            return int.MaxValue;

        return product << 1;
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public static int sat_mac32_16(int accumulator, short x, short y) {
        return sat_add32(accumulator, sat_mul32_16(x, y));
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public static int sat_msu32_16(int accumulator, short x, short y) {
        return sat_sub32(accumulator, sat_mul32_16(x, y));
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public static short sat_abs16(short value) {
        return value == short.MinValue
            ? short.MaxValue
            : (short)Math.Abs(value);
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public static int sat_abs32(int value) {
        return value == int.MinValue
            ? int.MaxValue
            : Math.Abs(value);
    }
}

