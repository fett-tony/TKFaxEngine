/// <summary>
/// IBM getopt.c behavior, including grouped options, required arguments,
/// slash options and the original optarg/optind/opterr names.
/// This class is intentionally stateful and not thread-safe, like the C API.
/// </summary>
public static class GetOpt {
    public const int EndOfOptions = -1;

    private static int _optind = 1;
    private static string? _currentArgument;
    private static int _position;

    public static string? optarg { get; private set; }

    public static int optind {
        get => _optind;
        set {
            _optind = value;
            _currentArgument = null;
            _position = 0;
            optarg = null;
        }
    }

    public static int opterr { get; set; } = 1;

    public static void Reset(int startIndex = 1) {
        _optind = startIndex;
        _currentArgument = null;
        _position = 0;
        optarg = null;
        opterr = 1;
    }

    public static int getopt(int argc, string[] argv, string opstring) {
        ArgumentNullException.ThrowIfNull(argv);
        ArgumentNullException.ThrowIfNull(opstring);

        int argumentLimit = Math.Min(Math.Max(argc, 0), argv.Length);
        optarg = null;

        if (_currentArgument is null || _position >= _currentArgument.Length) {
            _currentArgument = null;
            _position = 0;

            if (_optind >= argumentLimit)
                return EndOfOptions;

            string argument = argv[_optind++];
            if (string.IsNullOrEmpty(argument) ||
                (argument[0] != '-' && argument[0] != '/')) {
                _optind--;
                return EndOfOptions;
            }

            if (argument is "-" or "--")
                return EndOfOptions;

            _currentArgument = argument;
            _position = 1;
        }

        char option = _currentArgument[_position++];

        if (option == ':') {
            ClearCurrentArgument();
            return opterr != 0 ? '?' : ':';
        }

        int optionPosition = opstring.IndexOf(option);
        if (optionPosition < 0) {
            ClearCurrentArgument();
            return opterr != 0 ? '?' : option;
        }

        bool requiresArgument =
            optionPosition + 1 < opstring.Length &&
            opstring[optionPosition + 1] == ':';

        if (requiresArgument) {
            if (_position < _currentArgument.Length) {
                optarg = _currentArgument[_position..];
            } else if (_optind < argumentLimit) {
                optarg = argv[_optind++];
            } else {
                ClearCurrentArgument();
                return opterr != 0 ? '?' : option;
            }

            ClearCurrentArgument(keepOptArg: true);
        } else if (_position >= _currentArgument.Length) {
            ClearCurrentArgument();
        }

        return option;
    }

    private static void ClearCurrentArgument(bool keepOptArg = false) {
        _currentArgument = null;
        _position = 0;
        if (!keepOptArg)
            optarg = null;
    }
}

