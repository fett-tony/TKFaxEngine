    private static ReadOnlySpan<float> GetPhase(
        float[][] table,
        int phase) {
        if ((uint)phase >= CoefficientSets)
            throw new ArgumentOutOfRangeException(nameof(phase));

        return table[phase];
    }

    private static short[][] CreateFixedPoint(float[][] source) {
        short[][] result = new short[source.Length][];

        for (int phase = 0; phase < source.Length; phase++) {
            float[] sourcePhase = source[phase];
            short[] targetPhase = new short[sourcePhase.Length];

            for (int tap = 0; tap < sourcePhase.Length; tap++) {
                float scaled = sourcePhase[tap] * 32767.0f;
                int rounded = scaled >= 0.0f
                    ? (int)(scaled + 0.5f)
                    : (int)(scaled - 0.5f);

                targetPhase[tap] = checked((short)rounded);
            }

            result[phase] = targetPhase;
        }

        return result;
    }
