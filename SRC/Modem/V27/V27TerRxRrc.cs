    public static ReadOnlySpan<float> GetCoefficients(
        int bitRate,
        bool imaginary,
        int coefficientSet) {
        float[][] table = SelectTable(bitRate, imaginary);
        if ((uint)coefficientSet >= (uint)table.Length)
            throw new ArgumentOutOfRangeException(nameof(coefficientSet));

        return table[coefficientSet];
    }

    public static short[] GetFixedPointCoefficients(
        int bitRate,
        bool imaginary,
        int coefficientSet) {
        ReadOnlySpan<float> source = GetCoefficients(bitRate, imaginary, coefficientSet);
        short[] result = new short[source.Length];

        for (int i = 0; i < source.Length; i++)
            result[i] = ScaleToFixedPoint(source[i]);

        return result;
    }

    public static short ScaleToFixedPoint(float value) {
        double rounded = FixedPointScale * value + (value >= 0.0f ? 0.5 : -0.5);
        return checked((short)(int)rounded);
    }

    public static int GetCoefficientSetCount(int bitRate) => bitRate switch {
        2400 => Rx2400CoefficientSets,
        4800 => Rx4800CoefficientSets,
        _ => throw new ArgumentOutOfRangeException(
            nameof(bitRate), bitRate, "Only 2400 and 4800 bit/s are supported.")
    };

    public static float GetGain(int bitRate) => bitRate switch {
        2400 => Rx2400Gain,
        4800 => Rx4800Gain,
        _ => throw new ArgumentOutOfRangeException(
            nameof(bitRate), bitRate, "Only 2400 and 4800 bit/s are supported.")
    };

    private static float[][] SelectTable(int bitRate, bool imaginary) => bitRate switch {
        2400 => imaginary ? Rx2400Imaginary : Rx2400Real,
        4800 => imaginary ? Rx4800Imaginary : Rx4800Real,
        _ => throw new ArgumentOutOfRangeException(
            nameof(bitRate), bitRate, "Only 2400 and 4800 bit/s are supported.")
    };

